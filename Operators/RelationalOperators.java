public class RelationalOperators {
    public static void main(String args[]) {
        int A = 10;
        int B = 10;
        System.out.println(A == B);
        System.out.println(A != B);

        A = 15;
        B = 5;
        System.out.println(A > B);
        System.out.println(A < B);

        B = 15;
        System.out.println(A >= B);
        System.out.println(A <= B);
    }
}